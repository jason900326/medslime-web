function normalizeText(value: string) {
  return value
    .replace(/\s+/g, "")
    .replace(/[()（）]/g, "")
    .replace(/[、，,。．·・]/g, "")
    .trim();
}

export function getTaxonomySubjectKey(value: string): TaxonomySubjectKey | null {
  const text = normalizeText(value);

  if (text.includes("微生物") || text.includes("細菌") || text.includes("黴菌")) {
    return "microbiology";
  }
  if (text.includes("生物化學") || text.includes("臨床生化")) {
    return "biochemistry";
  }
  if (text.includes("生理") || text.includes("病理")) {
    return "physiology-pathology";
  }
  if (text.includes("血液") || text.includes("血庫")) {
    return "hematology-bloodbank";
  }
  if (
    text.includes("血清免疫") ||
    text.includes("臨床免疫") ||
    text.includes("病毒")
  ) {
    return "immunology-virology";
  }
  if (
    text.includes("分子檢驗") ||
    text.includes("鏡檢") ||
    text.includes("寄生蟲")
  ) {
    return "molecular-microscopy";
  }

  return null;
}

export function getAllowedSubtopics(
  subjectKey: TaxonomySubjectKey,
  topic: string,
): string[] {
  return SUBTOPIC_TAXONOMY_CATALOG[subjectKey]?.[topic] ?? [];
}

export function getAllowedTaxonomy(subjectKey: TaxonomySubjectKey) {
  return TOPIC_TAXONOMY_CATALOG[subjectKey].map((topic) => ({
    topic,
    subtopics: getAllowedSubtopics(subjectKey, topic),
  }));
}
